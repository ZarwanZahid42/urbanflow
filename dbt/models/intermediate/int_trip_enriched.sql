with
    trips as (
        select
            trip_id,
            vendor_id,
            pickup_datetime,
            dropoff_datetime,
            pickup_date_key,
            dropoff_date_key,
            pickup_time_key,
            dropoff_time_key,
            pickup_location_id,
            dropoff_location_id,
            passenger_count,
            trip_distance,
            rate_code_id,
            payment_type,
            store_and_forward_flag,
            fare_amount,
            extra,
            mta_tax,
            tip_amount,
            tolls_amount,
            improvement_surcharge,
            congestion_surcharge,
            airport_fee,
            cbd_congestion_fee,
            total_amount,
            trip_duration_minutes,
            average_speed_mph,
            fare_per_mile,
            tip_percentage,
            is_financial_adjustment,
            non_adjustment_revenue,
            financial_adjustment_amount,
            source_year,
            source_month,
            source_file,
            ingested_at_utc,
            bronze_run_id,
            silver_run_id,
            silver_processed_at_utc,
            gold_run_id,
            gold_processed_at_utc
        from {{ ref('stg_fact_trips') }}
    ),

    dates as (
        select
            date_key,
            calendar_date,
            year,
            quarter,
            month,
            month_name,
            week,
            day,
            day_of_week,
            day_name,
            is_weekend
        from {{ ref('stg_dim_date') }}
    ),

    times as (
        select
            time_key,
            hour,
            minute,
            hour_bucket,
            am_pm,
            time_of_day
        from {{ ref('stg_dim_time') }}
    ),

    locations as (
        select
            location_id,
            borough,
            zone,
            service_zone,
            borough_normalized,
            zone_normalized
        from {{ ref('stg_dim_location') }}
    )

select
    trips.trip_id,
    trips.vendor_id,
    trips.pickup_datetime,
    trips.dropoff_datetime,
    trips.pickup_date_key,
    trips.dropoff_date_key,
    trips.pickup_time_key,
    trips.dropoff_time_key,
    trips.pickup_location_id,
    trips.dropoff_location_id,
    pickup_date.calendar_date as pickup_date,
    pickup_date.year as pickup_year,
    pickup_date.quarter as pickup_quarter,
    pickup_date.month as pickup_month,
    pickup_date.month_name as pickup_month_name,
    pickup_date.week as pickup_week,
    pickup_date.day as pickup_day,
    pickup_date.day_of_week as pickup_day_of_week,
    pickup_date.day_name as pickup_day_name,
    pickup_date.is_weekend as pickup_is_weekend,
    dropoff_date.calendar_date as dropoff_date,
    dropoff_date.year as dropoff_year,
    dropoff_date.quarter as dropoff_quarter,
    dropoff_date.month as dropoff_month,
    dropoff_date.month_name as dropoff_month_name,
    dropoff_date.week as dropoff_week,
    dropoff_date.day as dropoff_day,
    dropoff_date.day_of_week as dropoff_day_of_week,
    dropoff_date.day_name as dropoff_day_name,
    dropoff_date.is_weekend as dropoff_is_weekend,
    pickup_time.hour as pickup_hour,
    pickup_time.minute as pickup_minute,
    pickup_time.hour_bucket as pickup_hour_bucket,
    pickup_time.am_pm as pickup_am_pm,
    pickup_time.time_of_day as pickup_time_of_day,
    dropoff_time.hour as dropoff_hour,
    dropoff_time.minute as dropoff_minute,
    dropoff_time.hour_bucket as dropoff_hour_bucket,
    dropoff_time.am_pm as dropoff_am_pm,
    dropoff_time.time_of_day as dropoff_time_of_day,
    pickup_location.borough as pickup_borough,
    pickup_location.zone as pickup_zone,
    pickup_location.service_zone as pickup_service_zone,
    pickup_location.borough_normalized as pickup_borough_normalized,
    pickup_location.zone_normalized as pickup_zone_normalized,
    dropoff_location.borough as dropoff_borough,
    dropoff_location.zone as dropoff_zone,
    dropoff_location.service_zone as dropoff_service_zone,
    dropoff_location.borough_normalized as dropoff_borough_normalized,
    dropoff_location.zone_normalized as dropoff_zone_normalized,
    trips.passenger_count,
    trips.trip_distance,
    trips.rate_code_id,
    trips.payment_type,
    trips.store_and_forward_flag,
    trips.fare_amount,
    trips.extra,
    trips.mta_tax,
    trips.tip_amount,
    trips.tolls_amount,
    trips.improvement_surcharge,
    trips.congestion_surcharge,
    trips.airport_fee,
    trips.cbd_congestion_fee,
    trips.total_amount,
    trips.trip_duration_minutes,
    trips.average_speed_mph,
    trips.fare_per_mile,
    trips.tip_percentage,
    trips.is_financial_adjustment,
    trips.non_adjustment_revenue,
    trips.financial_adjustment_amount,
    trips.source_year,
    trips.source_month,
    trips.source_file,
    trips.ingested_at_utc,
    trips.bronze_run_id,
    trips.silver_run_id,
    trips.silver_processed_at_utc,
    trips.gold_run_id,
    trips.gold_processed_at_utc
from trips
inner join dates as pickup_date on trips.pickup_date_key = pickup_date.date_key
inner join dates as dropoff_date on trips.dropoff_date_key = dropoff_date.date_key
inner join times as pickup_time on trips.pickup_time_key = pickup_time.time_key
inner join times as dropoff_time on trips.dropoff_time_key = dropoff_time.time_key
inner join locations as pickup_location
    on trips.pickup_location_id = pickup_location.location_id
inner join locations as dropoff_location
    on trips.dropoff_location_id = dropoff_location.location_id
